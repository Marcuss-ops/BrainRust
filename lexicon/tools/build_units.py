#!/usr/bin/env python3
"""Generate checked per-language unit packs from lexicon/units.json."""

from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "lexicon" / "units.json"
LANGUAGES = ROOT / "lexicon" / "languages"
OUTPUT = ROOT / "lexicon" / "units"
GENERATED = ROOT / "semantic-core" / "src" / "generated_units.rs"


def render() -> dict[Path, str]:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    if data.get("schema") != "units.v1":
        raise SystemExit(f"{SOURCE}: expected schema units.v1")
    dimensions = data.get("dimensions")
    if not isinstance(dimensions, list) or not dimensions or len(set(dimensions)) != len(dimensions):
        raise SystemExit(f"{SOURCE}: dimensions must be a non-empty unique list")
    expected = sorted(path.name for path in LANGUAGES.iterdir() if path.is_dir() and path.name != "fallback")
    languages = data.get("languages")
    if not isinstance(languages, dict) or sorted(languages) != expected:
        raise SystemExit(f"{SOURCE}: languages must exactly match lexicon/languages (excluding fallback)")
    files: dict[Path, str] = {}
    entries: list[str] = []
    for language in expected:
        row = languages[language]
        units = row.get("units")
        if not isinstance(units, list) or not units:
            raise SystemExit(f"{SOURCE}: {language} has no units")
        seen: dict[str, str] = {}
        for unit in units:
            dimension = unit.get("dimension")
            code = unit.get("code")
            factor = unit.get("factor_to_base")
            surfaces = unit.get("surfaces")
            if dimension not in dimensions or not isinstance(code, str) or not code:
                raise SystemExit(f"{SOURCE}: invalid dimension or code in {language}: {unit}")
            if not isinstance(factor, (int, float)) or not math.isfinite(factor) or factor <= 0:
                raise SystemExit(f"{SOURCE}: invalid factor_to_base in {language}: {unit}")
            if not isinstance(surfaces, list) or not surfaces or any(not isinstance(s, str) or not s.strip() for s in surfaces):
                raise SystemExit(f"{SOURCE}: invalid surfaces in {language}: {unit}")
            for surface in surfaces:
                key = surface.casefold()
                previous = seen.get(key)
                if previous is not None and previous != code:
                    raise SystemExit(f"{SOURCE}: ambiguous {language} surface {surface!r}: {previous} / {code}")
                seen[key] = code
        pack = {
            "schema": "units.v1",
            "language": language,
            "units": units,
            "qualifiers": row.get("qualifiers", {}),
            "predicates": row.get("predicates", {}),
        }
        path = OUTPUT / f"{language}.json"
        files[path] = json.dumps(pack, ensure_ascii=False, indent=2) + "\n"
        entries.append(
            f'    ("{language}", include_str!("../../lexicon/units/{language}.json")),'
        )
    files[OUTPUT / "index.json"] = json.dumps(
        {"schema": "units_index.v1", "languages": expected},
        ensure_ascii=False,
        indent=2,
    ) + "\n"
    files[GENERATED] = (
        "// @generated by lexicon/tools/build_units.py; do not edit.\n"
        "#[rustfmt::skip]\n"
        "pub const UNITS: &[(&str, &str)] = &[\n"
        + "\n".join(entries)
        + "\n];\n"
    )
    return files


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="check generated files without writing")
    args = parser.parse_args()
    expected = render()
    stale = [path for path, content in expected.items() if not path.is_file() or path.read_text(encoding="utf-8") != content]
    if args.check:
        if stale:
            for path in stale:
                print(f"stale generated unit asset: {path.relative_to(ROOT)}")
            return 1
        print(f"unit lexicon OK: {len(expected) - 2} languages")
        return 0
    for path, content in expected.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    print(f"generated {len(expected) - 2} language unit packs")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
